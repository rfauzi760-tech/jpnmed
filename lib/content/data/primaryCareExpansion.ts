import { D, type DiseaseRow } from '../builders';
import type { ClinicalLine, Disease } from '../schema';
import { kanaToRomajiFull } from '@/lib/utils/romaji';

type PrimaryCareSeed = Omit<DiseaseRow, 'explanationSupport' | 'causeSupport'> & {
  explanationKana: string;
  explanationIndonesian: string;
  explanationEnglish: string;
  causeKana: string;
  causeIndonesian: string;
  causeEnglish: string;
};

const line = (japanese: string, kana: string, indonesian: string, english: string): ClinicalLine => ({
  japanese,
  kana,
  romaji: kanaToRomajiFull(kana),
  indonesian,
  english,
});

function disease(seed: PrimaryCareSeed): Disease {
  const {
    explanationKana,
    explanationIndonesian,
    explanationEnglish,
    causeKana,
    causeIndonesian,
    causeEnglish,
    ...row
  } = seed;

  return D({
    ...row,
    explanationSupport: line(row.explain, explanationKana, explanationIndonesian, explanationEnglish),
    causeSupport: line(row.cause ?? '', causeKana, causeIndonesian, causeEnglish),
  });
}

