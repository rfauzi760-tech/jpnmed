/** surface → kana, parsed once at module load. */
function parseCommon(): Record<string, string> {
  const map: Record<string, string> = {};
  for (const pair of COMMON_RAW.split(/\s*,\s*/)) {
    if (!pair) continue;
    const eq = pair.indexOf('=');
    if (eq <= 0) continue;
    const surface = pair.slice(0, eq);
    const reading = pair.slice(eq + 1);
    if (surface && reading && !(surface in map)) map[surface] = reading;
  }
  return map;
}

export const COMMON_FURIGANA: Record<string, string> = parseCommon();
